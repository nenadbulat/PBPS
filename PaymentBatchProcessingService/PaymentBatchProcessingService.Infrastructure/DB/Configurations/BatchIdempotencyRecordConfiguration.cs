using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using PaymentBatchProcessingService.Domain.Entities;
using PaymentBatchProcessingService.Domain.Helpers;
using PaymentBatchProcessingService.Infrastructure.DB.Models;

namespace PaymentBatchProcessingService.Infrastructure.DB.Configurations;

public sealed class BatchIdempotencyRecordConfiguration : IEntityTypeConfiguration<BatchIdempotencyRecord>
{
    public void Configure(EntityTypeBuilder<BatchIdempotencyRecord> builder)
    {
        //SQL table name
        builder.ToTable("BatchIdempotencyRecords");

        //Primary key configuration, GUID is generated by the application, not the database
        builder.HasKey(x => x.Id);
        builder.Property(x => x.Id).ValueGeneratedNever();

        //IdempotencyKey is required, has a maximum length of 128, and is stored as non-Unicode in the database
        builder.Property(x => x.IdempotencyKey).HasMaxLength(Constants.IdempotencyKeyLength).IsUnicode(false).IsRequired();

        //RequestFingerprint is required, has a maximum length of 64, and is stored as non-Unicode in the database
        builder.Property(x => x.RequestFingerprint).HasMaxLength(Constants.RequestFingerprintLength).IsUnicode(false).IsRequired();

        //CreatedAtUtc is required and is stored as UTC in the database
        builder.Property(x => x.CreatedAtUtc).HasColumnType("datetime2")
            .HasConversion(
                value => value,
                value => DateTime.SpecifyKind(value, DateTimeKind.Utc)).IsRequired();

        //Has one PaymentBatch and one Tenant, with foreign key constraints and restricted delete behavior
        builder.HasOne<PaymentBatch>().WithMany().HasForeignKey(x => x.BatchId).OnDelete(DeleteBehavior.Restrict);
        builder.HasOne<Tenant>().WithMany().HasForeignKey(x => x.TenantId).OnDelete(DeleteBehavior.Restrict);

        //Ensure that the combination of TenantId and IdempotencyKey is unique to prevent duplicate processing
        builder.HasIndex(x => new { x.TenantId, x.IdempotencyKey }).IsUnique();
    }
}
